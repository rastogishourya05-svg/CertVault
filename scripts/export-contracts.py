"""Export the API schema and TypeScript models without adding a codegen runtime."""

import json
import sys
from pathlib import Path

from apps.api.main import app


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts_type(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        if not schema.get("properties"):
            return "Record<string, unknown>"
        required = schema.get("required", [])
        return (
            "{ "
            + "; ".join(
                f"{json.dumps(k)}{'' if k in required else '?'}: {ts_type(v)}"
                for k, v in schema.get("properties", {}).items()
            )
            + " }"
        )
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    spec = app.openapi()
    outputs = {Path("docs/openapi.json"): json.dumps(spec, indent=2) + "\n"}
    models = spec["components"]["schemas"]
    outputs[Path("apps/web/src/lib/generated.ts")] = (
        "// Generated by scripts/export-contracts.py. Do not edit.\n"
        + "\n".join(
            f"export type {name} = {ts_type(schema)};" for name, schema in sorted(models.items())
        )
        + "\n"
    )
    for path, content in outputs.items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(
                    f"API contract drift: run python scripts/export-contracts.py ({path})"
                )
        else:
            path.write_text(content, encoding="utf-8")
    print(
        "OpenAPI and TypeScript contracts match"
        if "--check" in sys.argv
        else "Exported OpenAPI and TypeScript contracts"
    )


if __name__ == "__main__":
    main()
